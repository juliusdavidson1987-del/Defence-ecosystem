#!/usr/bin/env node
/**
 * Backfill relationship edges from the existing affiliation layer (v4.13.0).
 * -------------------------------------------------------------------------
 * Reads data.json (nodes + their { affiliation:{net,role,note} }), resolves each
 * affiliation's `net` to a target node and its `role` to a relationship_type, and
 * writes:
 *   migrations/2026-10-10-relationships-backfill.sql  — idempotent INSERTs (clean matches)
 *   relationships-review.csv                          — everything it could NOT resolve
 *                                                        deterministically, for you to classify
 * Deterministic only: no AI, no guessing. Anything uncertain goes to the CSV, not the DB.
 *
 *   node scripts/backfill-relationships.mjs [data.json]
 */
import fs from 'node:fs';

const DATA = process.argv[2] || 'data.json';
const data = JSON.parse(fs.readFileSync(DATA, 'utf8'));
const nodes = data.nodes || [];

// ---- node lookup indexes ---------------------------------------------------
const byId = new Set(nodes.map(n => n.id));
// normalise a name for matching: lowercase, drop parentheticals & punctuation,
// drop a few corporate/alliance qualifiers, collapse spaces. Conservative — we
// would rather miss (→ CSV) than mis-link.
const strip = new Set(['group','plc','ltd','limited','inc','corp','corporation','co','holdings','international','nato','the']);
function norm(s){
  return String(s || '')
    .toLowerCase()
    .replace(/\(.*?\)/g, ' ')
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9 ]/g, ' ')
    .split(/\s+/).filter(w => w && !strip.has(w)).join(' ')
    .trim();
}
const normLabel = new Map();                      // normalised label -> [ids]
nodes.forEach(n => {
  const k = norm(n.label);
  if (!k) return;
  (normLabel.get(k) || normLabel.set(k, []).get(k)).push(n.id);
});
function resolveNet(net){
  const k = norm(net);
  if (!k) return null;
  if (byId.has(k.replace(/ /g, '_'))) return k.replace(/ /g, '_'); // e.g. "nssif" -> id nssif
  const hit = normLabel.get(k);
  if (hit && hit.length === 1) return hit[0];      // unique label match only
  return null;                                     // ambiguous or none -> review
}

// ---- role -> relationship_type (membership vs corporate family) ------------
const MEMBER_ROLES = ['centre of excellence','coe','accelerator','test centre','test center','catapult','centre','center','fund-of-funds partner','fund of funds partner','partner','accredited','network'];
const CORP_ROLES   = ['arm','parent','subsidiary','division','mission systems','space systems','naval ships','submarines','maritime services','helicopters','air','land','sea','aviation','nuclear','digital intelligence','electronic systems','systems'];
function classify(role){
  const r = (role || '').toLowerCase().trim();
  if (!r) return null;
  if (MEMBER_ROLES.some(x => r.includes(x))) return 'member_of';
  if (CORP_ROLES.some(x => r === x || r.endsWith(' '+x) || r.includes(x))) return 'subsidiary_of';
  return null;                                     // unknown -> unclassified/review
}

// ---- walk the affiliations -------------------------------------------------
const edges = [], review = [];
const counts = {};
nodes.forEach(n => {
  const a = n.affiliation;
  if (!a || !a.net) return;
  const target = resolveNet(a.net);
  const type = classify(a.role) || 'unclassified';
  if (!target) {                                   // couldn't place the net -> review
    review.push({ id: n.id, label: n.label, net: a.net, role: a.role || '', note: a.note || '', reason: 'net did not resolve to a node' });
    return;
  }
  if (target === n.id) {                           // self-loop guard
    review.push({ id: n.id, label: n.label, net: a.net, role: a.role || '', note: a.note || '', reason: 'net resolved to itself' });
    return;
  }
  if (type === 'unclassified') {
    review.push({ id: n.id, label: n.label, net: a.net, role: a.role || '', note: a.note || '', reason: 'role did not map to a type', target });
    return;
  }
  edges.push({ src: n.id, tgt: target, type, role: a.role || '', note: a.note || '' });
  counts[type] = (counts[type] || 0) + 1;
});

// ---- emit SQL --------------------------------------------------------------
const esc = s => String(s == null ? '' : s).replace(/'/g, "''");
const sqlRows = edges.map(e => {
  const attrs = JSON.stringify({ role: e.role || undefined, backfilled_from: 'affiliation' });
  const note = e.note ? `'${esc(e.note)}'` : 'null';
  return `  ('${esc(e.src)}','${esc(e.tgt)}','${e.type}',true,'unverified','curated',${note},'${esc(attrs)}'::jsonb)`;
}).join(',\n');

const sql = `-- ============================================================================
-- v4.13.0 — Relationship edges: BACKFILL  (stage B, generated by
-- scripts/backfill-relationships.mjs on ${new Date().toISOString().slice(0,10)})
-- ----------------------------------------------------------------------------
-- ${edges.length} edges derived deterministically from the affiliation layer.
-- Run AFTER the schema migration. Idempotent (on conflict do nothing).
-- Everything that could not be resolved is in relationships-review.csv (NOT here).
-- ============================================================================
insert into public.relationships
  (source_node_id, target_node_id, relationship_type, directed, evidence_status, origin, evidence_note, attributes)
values
${sqlRows}
on conflict (source_node_id, target_node_id, relationship_type, coalesce(valid_from,'0001-01-01')) do nothing;
`;
fs.writeFileSync('migrations/2026-10-10-relationships-backfill.sql', edges.length ? sql : '-- no resolvable edges\n');

// ---- emit review CSV -------------------------------------------------------
const csvEsc = s => { const v = String(s == null ? '' : s); return /[",\n]/.test(v) ? '"' + v.replace(/"/g, '""') + '"' : v; };
const csv = ['source_id,source_label,net,role,note,reason,suggested_target']
  .concat(review.map(r => [r.id, r.label, r.net, r.role, r.note, r.reason, r.target || ''].map(csvEsc).join(',')))
  .join('\n');
fs.writeFileSync('relationships-review.csv', csv + '\n');

// ---- summary ---------------------------------------------------------------
console.log(`Affiliations seen : ${nodes.filter(n => n.affiliation && n.affiliation.net).length}`);
console.log(`Edges resolved    : ${edges.length}`);
Object.entries(counts).sort((a,b)=>b[1]-a[1]).forEach(([t,c]) => console.log(`   ${c}  ${t}`));
console.log(`For review (CSV)  : ${review.length}`);
const byReason = {}; review.forEach(r => byReason[r.reason] = (byReason[r.reason]||0)+1);
Object.entries(byReason).forEach(([r,c]) => console.log(`   ${c}  ${r}`));
